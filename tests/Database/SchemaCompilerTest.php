<?php

declare(strict_types=1);

namespace Kabuto\Tests\Database;

use Kabuto\Database\DatasourceDefinition;
use Kabuto\Database\FieldDefinition;
use Kabuto\Database\ModelDefinition;
use Kabuto\Database\SchemaCompiler;
use Kabuto\Tests\TestCase;

final class SchemaCompilerTest extends TestCase
{
    public function testAutoIncrementPrimaryKeyPerDriver(): void
    {
        self::assertSame('"id" INTEGER PRIMARY KEY AUTOINCREMENT', SchemaCompiler::autoIncrementPkFor('sqlite'));
        self::assertSame('`id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY', SchemaCompiler::autoIncrementPkFor('mysql'));
        self::assertSame('"id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', SchemaCompiler::autoIncrementPkFor('pgsql'));
        self::assertSame('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', SchemaCompiler::autoIncrementPkFor('postgresql', 'id', true));
    }

    public function testSqliteDdl(): void
    {
        $sql = $this->compiler('sqlite')->createTable($this->model());

        self::assertStringContains('CREATE TABLE "base_accounts"', $sql);
        self::assertStringContains('"id" INTEGER PRIMARY KEY AUTOINCREMENT', $sql);
        self::assertStringContains('"active" BOOLEAN NOT NULL DEFAULT 1', $sql);
        self::assertStringContains('"meta" TEXT', $sql);
        self::assertStringContains('"balance" DECIMAL(10,2) NOT NULL DEFAULT 0', $sql);
        self::assertStringContains('"created_at" TEXT DEFAULT CURRENT_TIMESTAMP', $sql);
        self::assertStringContains('UNIQUE ("email")', $sql);
        self::assertStringContains('"name" VARCHAR(100) NOT NULL', $sql);
    }

    public function testMysqlDdl(): void
    {
        $sql = $this->compiler('mysql')->createTable($this->model());

        self::assertStringContains('CREATE TABLE `base`.`accounts`', $sql);
        self::assertStringContains('`id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY', $sql);
        self::assertStringContains('`active` TINYINT(1) NOT NULL DEFAULT 1', $sql);
        self::assertStringContains('`meta` JSON', $sql);
        self::assertStringContains('`created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP', $sql);
        self::assertStringContains("`kind` ENUM('a','b')", $sql);
    }

    public function testPgsqlDdl(): void
    {
        $sql = $this->compiler('pgsql')->createTable($this->model());

        self::assertStringContains('CREATE TABLE "base"."accounts"', $sql);
        self::assertStringContains('"id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql);
        self::assertStringContains('"active" BOOLEAN NOT NULL DEFAULT TRUE', $sql);
        self::assertStringContains('"meta" JSONB', $sql);
        self::assertStringContains('"balance" DECIMAL(10,2) NOT NULL DEFAULT 0', $sql);
        self::assertStringContains('"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP', $sql);
        self::assertStringContains('UNIQUE ("email")', $sql);
    }

    public function testBooleanDefaultsAreDriverNative(): void
    {
        $field = new FieldDefinition('flag', 'boolean', null, [], [], false, true);

        self::assertStringContains('DEFAULT 0', $this->compiler('sqlite')->column($field));
        self::assertStringContains('DEFAULT 0', $this->compiler('mysql')->column($field));
        self::assertStringContains('DEFAULT FALSE', $this->compiler('pgsql')->column($field));
    }

    public function testTableReferencesPerDriver(): void
    {
        self::assertSame('"base_accounts"', $this->compiler('sqlite')->tableRef('base', 'accounts'));
        self::assertSame('`base`.`accounts`', $this->compiler('mysql')->tableRef('base', 'accounts'));
        self::assertSame('"base"."accounts"', $this->compiler('pgsql')->tableRef('base', 'accounts'));

        self::assertSame('base_accounts', $this->compiler('sqlite')->physicalTable('base', 'accounts'));
        self::assertSame('accounts', $this->compiler('mysql')->physicalTable('base', 'accounts'));
        self::assertSame('', $this->compiler('sqlite')->schemaOf('base'));
        self::assertSame('base', $this->compiler('pgsql')->schemaOf('base'));
        self::assertSame('base', $this->compiler('mysql')->schemaOf('base'));
    }

    public function testCreateIndexGuardsIfNotExists(): void
    {
        $sqlite = $this->compiler('sqlite')->createIndex('name_idx', 'base', 'accounts', 'name', true);
        $mysql = $this->compiler('mysql')->createIndex('name_idx', 'base', 'accounts', 'name', true);
        $pgsql = $this->compiler('pgsql')->createIndex('name_idx', 'base', 'accounts', 'name', true);

        self::assertStringContains('IF NOT EXISTS', $sqlite);
        self::assertStringContains('IF NOT EXISTS', $pgsql);
        self::assertFalse(str_contains($mysql, 'IF NOT EXISTS'));
        self::assertStringContains('ON "base_accounts"', $sqlite);
        self::assertStringContains('ON `base`.`accounts`', $mysql);
        self::assertStringContains('ON "base"."accounts"', $pgsql);
    }

    public function testSplitRefParsesQualifiedNames(): void
    {
        self::assertSame(['db', 'tbl'], \Kabuto\Database\SchemaIntrospector::splitRef('`db`.`tbl`'));
        self::assertSame(['sch', 'tbl'], \Kabuto\Database\SchemaIntrospector::splitRef('"sch"."tbl"'));
        self::assertSame(['sch', 'tbl'], \Kabuto\Database\SchemaIntrospector::splitRef('sch.tbl'));
        self::assertSame([null, 'tbl'], \Kabuto\Database\SchemaIntrospector::splitRef('tbl'));
        self::assertSame([null, 'base_users'], \Kabuto\Database\SchemaIntrospector::splitRef('"base_users"'));
    }

    private function compiler(string $driver): SchemaCompiler
    {
        return new SchemaCompiler(new DatasourceDefinition('db', $driver, ['base']));
    }

    private function model(): ModelDefinition
    {
        return new ModelDefinition('Account', 'accounts', 'base', 'db', [
            'id' => new FieldDefinition('id', 'increments'),
            'name' => new FieldDefinition('name', 'string', 100),
            'email' => new FieldDefinition('email', 'string', 150, ['unique']),
            'active' => new FieldDefinition('active', 'boolean', null, [], [], true, true),
            'balance' => new FieldDefinition('balance', 'decimal', null, [], [], 0, true),
            'meta' => new FieldDefinition('meta', 'json', null, ['nullable']),
            'kind' => new FieldDefinition('kind', 'enum', null, ['nullable'], ['a', 'b']),
            'created_at' => new FieldDefinition('created_at', 'timestamp', null, ['useCurrent', 'nullable']),
        ]);
    }
}
